import { Tabs } from 'expo-router';
import { PageDock } from '@/components/PageDock';

/**
 * 会话 / 设置两页共用的框架。
 *
 * **为什么从栈改成 tabs。** 上一版这两页是栈上的两条路由，靠 `router.replace`
 * 互切。owner 实测到两个毛病，都是那个结构必然带来的：
 *
 *   底部那条会整个消失再出现   dock 写在每一页里，换页 = 换组件 = dock 重建
 *   永远左出右进               栈的转场只有「推进/退回」两种方向，而这两页是
 *                              平级的，没有谁在谁前面
 *
 * 改成 tabs 之后 dock 活在页面**之外**（作为 tabBar），换页时它根本不参与；
 * 方向也由 tab 的前后次序决定，从会话到设置往左、反过来往右。
 *
 * 与根 _layout 里「栈式导航，不是标签页」那条注释不冲突：那条针对的是
 * **不要凭空造出几个平级的地方**。会话和设置本来就是两个独立的页，
 * 这里只是把已有的关系如实表达出来，没有新增任何一处。会话详情、新建、配对
 * 仍然是栈上的推进——那些确实有前后关系。
 */
export default function TabsLayout() {
  return (
    <Tabs
      screenOptions={{
        headerShown: false,
        /**
         * **tab 之间左右横移。**
         *
         * 这条来回改过两次，记清楚免得又翻烧饼：
         *
         *   一开始  'shift'，理由是「用 'none' 会变成硬切，两页之间就没有方位感」
         *   后来改  'none'，理由是「滑动表达的是层级，而 tab 是平级；
         *           而且一天切几十上百次，每次付 200ms 不划算」
         *   现在    改回 'shift'
         *
         * 改回来的依据不是那两条道理谁更对，是 **owner 的实际使用**：
         * 「会话和设置的切换没有左右切换动画」。而且这一版的底部那条已经是系统的
         * 分段控件——它自己的滑块就在左右滑，页面跟着横移才是同一件事的两半；
         * 页面硬切、滑块滑动，读起来是两回事在同时发生。
         *
         * 那条「平级不该有方位」的道理在**这个控件**上不成立：分段控件的语义
         * 本来就是「一条轨道上的若干格」，它有左右，页面跟着走是如实表达。
         */
        animation: 'shift',
      }}
      tabBar={(props) => <PageDock {...props} />}
    >
      <Tabs.Screen name="index" />
      <Tabs.Screen name="about" />
    </Tabs>
  );
}
