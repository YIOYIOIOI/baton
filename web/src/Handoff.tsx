/** 球心与半径，取自 mask-ball.png 的包围盒 (290,597)-(509,813)。 */
const BALL = { cx: 399.5, cy: 705, r: 109.5 };

/**
 * 球还在下面那只手里时，相对设计稿球心的位移。
 *
 * 量的是 mask-lower.png 每一列最高的那个点：四根手指尖分别落在
 * x≈160/250/355/430、y≈837/780/812/901。球心放在 (300, 872)，
 * 它的上半截从指尖上方露出来、下半截被手指挡住——握着，而不是悬着。
 */
const REST = { x: 300 - BALL.cx, y: 872 - BALL.cy };

/**
 * 从手里到半空走的是一段弧，不是直线：先往上拔、再往右送。
 * 二次贝塞尔，控制点压在起点正上方——抛东西的时候手先往上抬。
 */
function along(p: number): { x: number; y: number } {
  const q = 1 - p;
  const c = { x: REST.x * 0.9, y: REST.y * 0.25 };
  return {
    x: q * q * REST.x + 2 * q * p * c.x,
    y: q * q * REST.y + 2 * q * p * c.y,
  };
}

export type HandoffPhase = 'idle' | 'toss' | 'miss';

export function Handoff({
  progress, phase = 'idle', className,
}: {
  /** 0–1。不传 = 球悬在两手之间（首屏） */
  progress?: number;
  phase?: HandoffPhase;
  className?: string;
}) {
  const p = progress === undefined ? 1 : Math.min(1, Math.max(0, progress));
  const at = along(p);
  const cls = ['handoff'];
  if (p >= 1) cls.push('is-ready');
  if (phase !== 'idle') cls.push(`is-${phase}`);
  if (className) cls.push(className);

  return (
    <svg
      className={cls.join(' ')}
      viewBox="0 0 706 1391"
      aria-hidden="true"
      focusable="false"
    >
      {/* 外层管进度（跟着码走），里层管最后那一下（接住 / 掉回来）——
          两个 transform 各管各的，叠起来才不会互相覆盖 */}
      <g className="handoff-track" style={{ transform: `translate(${at.x}px, ${at.y}px)` }}>
        <circle className="handoff-ball" cx={BALL.cx} cy={BALL.cy} r={BALL.r} />
      </g>
      <path className="handoff-hand is-upper" d={UPPER} />
      <path className="handoff-hand is-lower" d={LOWER} />
      <path className="handoff-rays" d={RAYS} />
    </svg>
  );
}
