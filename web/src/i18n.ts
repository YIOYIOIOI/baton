export type Locale = 'en' | 'zh';

/** Resolve user preference + browser/OS language into an active UI locale. */
export function resolveLocale(
  pref: LocalePref = 'auto',
  navLang: string | null = typeof navigator !== 'undefined' ? navigator.language : null,
): Locale {
  if (pref === 'en' || pref === 'zh') return pref;
  if (!navLang) return 'zh';
  return /^zh\b/i.test(navLang) ? 'zh' : 'en';
}

