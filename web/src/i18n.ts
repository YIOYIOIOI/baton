export const WEB_LOCALES = { en: EN, zh: ZH } as const;

export function translate(locale: Locale, key: MsgKey, vars?: Record<string, string | number>): string {
  let out = WEB_LOCALES[locale][key] ?? EN[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      out = out.replaceAll(`{${k}}`, String(v));
    }
  }
  return out;
}

export function t(key: MsgKey, vars?: Record<string, string | number>): string {
  return translate(resolveLocale(getPrefs().locale), key, vars);
}

export function useI18n() {
  const { locale: pref } = usePrefs();
  const locale = resolveLocale(pref);
  const tr = (key: MsgKey, vars?: Record<string, string | number>) => translate(locale, key, vars);
  return { locale, pref, t: tr };
}
